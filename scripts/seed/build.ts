/**
 * Deterministic seed builder: data/seed/*.json + data/curation/* → one SQL file.
 * Same inputs always produce byte-identical output (no clocks, no Math.random).
 *
 * Used by scripts/build-seed.ts (writes .data/seed.sql) and by the unit tests (in memory).
 */
import { createHash } from 'node:crypto';
import { PIXELS, SECTION_GROUPS, SECTION_TYPES } from '../../src/lib/taxonomy.ts';
import { REBUILD_DERIVED_SQL } from '../../src/server/repo/maintenance.ts';
import { normalizeDomain, slugify } from '../../src/server/lib/slug.ts';
import { loadSeedInputs, type AppInput, type SeedInputs } from './inputs.ts';
import { planStoreCaptures, type LayoutApp } from './layout.ts';
import {
  dollarsToCents,
  humanizeSlug,
  isScrapedSearchTitle,
  parseLongDate,
  priceToCents,
} from './normalize.ts';
import { SqlWriter, type Row } from './sql.ts';
import { parseTeardown } from './teardowns.ts';

/** Bump when the builder's output format changes (feeds data_version). */
const BUILDER_VERSION = '1';

export const SEED_CONSTANTS = {
  dataAsOf: '2026-11-17',
  sourceId: 'storepeek-scan-2026-11-17',
  sourceLabel: 'StorePeek scan of 930 Shopify stores, 17 Nov 2026 (pre-v7 rules)',
  rulesVersion: 'pre-v7',
  appStoreSourceLabel: 'Shopify App Store listing',
} as const;

const CATALOG_TS = `${SEED_CONSTANTS.dataAsOf}T00:00:00.000Z`;

export interface SeedReport {
  dataVersion: string;
  counts: Record<string, number>;
  warnings: string[];
  /** Detection counts per canonical app slug (from detections-930.json). */
  appStoreCounts: Record<string, number>;
  themeStoreCounts: Record<string, number>;
  shotHeights: Array<{ domain: string; page: string; device: string; height: number }>;
}

export interface SeedResult {
  sql: string;
  report: SeedReport;
}

interface AppRecord {
  id: number;
  slug: string;
  input: AppInput;
  profile: 'full' | 'basic';
  categoryName: string;
}

const iso = (ts: string) => new Date(ts).toISOString();

export function buildSeedFromRoot(root: string): SeedResult {
  return buildSeed(loadSeedInputs(root));
}

export function buildSeed(inputs: SeedInputs): SeedResult {
  const warnings: string[] = [];
  const warn = (msg: string) => warnings.push(msg);
  const w = new SqlWriter();

  const hash = createHash('sha256').update(`builder:${BUILDER_VERSION}\n`);
  for (const f of inputs.rawFiles) hash.update(`${f.name}\n${f.content}\n`);
  const dataVersion = hash.digest('hex').slice(0, 12);

  w.comment(`Generated by scripts/build-seed.ts — do not edit. data_version=${dataVersion}`);
  w.comment('Clear seeded tables (reverse dependency order) so the file can be re-applied.');
  for (const table of [
    'search_index',
    'store_similar',
    'theme_app_usage',
    'app_co_installs',
    'theme_stats',
    'app_stats',
    'teardown_notes',
    'teardowns',
    'comparisons',
    'section_tags',
    'sections',
    'screenshots',
    'pages',
    'scans',
    'store_pixels',
    'store_unresolved_apps',
    'store_apps',
    'store_themes',
    'stores',
    'store_categories',
    'affiliate_links',
    'affiliate_programs',
    'app_aliases',
    'apps',
    'app_categories',
    'theme_tags',
    'theme_presets',
    'themes',
    'section_types',
    'meta',
  ]) {
    w.raw(`DELETE FROM ${table}`);
  }

  // ------------------------------------------------------------------------------------------
  // Detection-derived counts (single source of truth for usage numbers)
  // ------------------------------------------------------------------------------------------
  const detections = inputs.detections.map((d) => {
    const domain = normalizeDomain(d.domain);
    if (!domain) throw new Error(`Invalid domain in detections: ${d.domain}`);
    return { ...d, domain };
  });
  const scannedTotal = detections.length;

  // ------------------------------------------------------------------------------------------
  // Meta
  // ------------------------------------------------------------------------------------------
  const allAppInputs = [...inputs.apps, ...inputs.appsExtra];
  const checkedDays = allAppInputs
    .map((a) => a.app_store_checked_on)
    .filter((d): d is string => typeof d === 'string')
    .sort();
  w.comment('meta');
  w.insert(
    'meta',
    Object.entries({
      data_version: dataVersion,
      data_as_of: SEED_CONSTANTS.dataAsOf,
      scanned_total: String(scannedTotal),
      rules_version: SEED_CONSTANTS.rulesVersion,
      source_id: SEED_CONSTANTS.sourceId,
      source_label: SEED_CONSTANTS.sourceLabel,
      app_store_checked_from: checkedDays[0] ?? SEED_CONSTANTS.dataAsOf,
      app_store_checked_to: checkedDays[checkedDays.length - 1] ?? SEED_CONSTANTS.dataAsOf,
      schema_version: '1',
    }).map(([key, value]) => ({ key, value, updated_at: CATALOG_TS })),
  );

  // ------------------------------------------------------------------------------------------
  // Section types (from the shared taxonomy)
  // ------------------------------------------------------------------------------------------
  w.comment('section_types');
  w.insert(
    'section_types',
    SECTION_TYPES.map((t, i) => ({
      slug: t.slug,
      name: t.name,
      group_slug: t.group,
      group_name: SECTION_GROUPS.find((g) => g.slug === t.group)?.name ?? t.group,
      description: t.description,
      position: i,
    })),
  );

  // ------------------------------------------------------------------------------------------
  // App categories + apps (with alias merging for duplicate App Store listings)
  // ------------------------------------------------------------------------------------------
  const categoryNames = [
    ...new Set([...inputs.categories, ...allAppInputs.map((a) => a.category)]),
  ].sort((a, b) => a.localeCompare(b));
  const categoryId = new Map(categoryNames.map((name, i) => [name, i + 1]));
  w.comment('app_categories');
  w.insert(
    'app_categories',
    categoryNames.map((name, i) => ({ id: i + 1, slug: slugify(name), name, position: i })),
  );

  // Two detection rules can point at the same App Store listing. Keep the most-detected slug
  // as the app and record the others as aliases.
  const byHandle = new Map<string, AppInput[]>();
  for (const a of allAppInputs) {
    if (!a.app_store_handle || isScrapedSearchTitle(a.name)) continue;
    byHandle.set(a.app_store_handle, [...(byHandle.get(a.app_store_handle) ?? []), a]);
  }
  const aliasOf = new Map<string, string>();
  for (const group of byHandle.values()) {
    if (group.length < 2) continue;
    const [canonical, ...rest] = [...group].sort(
      (x, y) => y.scan.stores - x.scan.stores || x.slug.localeCompare(y.slug),
    );
    if (!canonical) continue;
    for (const r of rest) {
      aliasOf.set(r.slug, canonical.slug);
      warn(`app alias: '${r.slug}' merged into '${canonical.slug}' (same listing)`);
    }
  }

  const apps: AppRecord[] = [];
  const appBySlug = new Map<string, AppRecord>();
  const fullSlugs = new Set(inputs.apps.map((a) => a.slug));
  for (const input of allAppInputs) {
    if (aliasOf.has(input.slug) || appBySlug.has(input.slug)) continue;
    const rec: AppRecord = {
      id: apps.length + 1,
      slug: input.slug,
      input,
      profile: fullSlugs.has(input.slug) ? 'full' : 'basic',
      categoryName: input.category,
    };
    apps.push(rec);
    appBySlug.set(rec.slug, rec);
  }
  const resolveApp = (detectionSlug: string): AppRecord | undefined =>
    appBySlug.get(aliasOf.get(detectionSlug) ?? detectionSlug);

  w.comment('apps');
  w.insert(
    'apps',
    apps.map(({ id, slug, input: a, profile, categoryName }) => {
      const scraped = isScrapedSearchTitle(a.name);
      if (scraped) warn(`app '${slug}': scraped search-page title replaced by developer name`);
      const listingUrl = scraped ? null : a.app_store_url;
      const isAppStore = listingUrl?.startsWith('https://apps.shopify.com/') ?? false;
      const plans = (a.plans ?? []).map((p) => ({
        name: p.name,
        price_label: p.price,
        price_cents: priceToCents(p.price),
        period: p.period ?? null,
        trial_days: p.trial_days ?? null,
        features: p.features ?? [],
      }));
      // A 0.0 rating with no reviews means "not rated yet", not a bad rating.
      const rating = a.rating === 0 && !a.reviews ? null : a.rating;
      return {
        id,
        slug,
        app_store_handle: scraped ? null : a.app_store_handle,
        name: scraped ? (a.developer ?? humanizeSlug(slug)) : a.name,
        developer: a.developer,
        category_id: categoryId.get(categoryName) ?? null,
        app_store_category: a.app_store_category ?? null,
        tagline: a.tagline,
        rating,
        reviews: a.reviews,
        icon_url: a.icon_url,
        app_store_url: isAppStore ? listingUrl : null,
        website_url: isAppStore ? null : listingUrl,
        launched_on: parseLongDate(a.launched),
        built_for_shopify: a.built_for_shopify ?? null,
        free_plan: a.free_plan ?? null,
        from_price_cents: dollarsToCents(a.from_price),
        trial_days: a.trial_days ?? null,
        plans_json: profile === 'full' ? JSON.stringify(plans) : null,
        features_json: a.features ? JSON.stringify(a.features) : null,
        works_with_json: a.works_with ? JSON.stringify(a.works_with) : null,
        languages_json: a.languages ? JSON.stringify(a.languages) : null,
        checked_on: a.app_store_checked_on ?? null,
        profile,
        status: 'active',
        created_at: CATALOG_TS,
        updated_at: CATALOG_TS,
      };
    }),
  );
  w.insert(
    'app_aliases',
    [...aliasOf.entries()].map(([slug, target]) => ({
      slug,
      app_id: appBySlug.get(target)?.id ?? null,
    })),
  );

  // ------------------------------------------------------------------------------------------
  // Themes
  // ------------------------------------------------------------------------------------------
  const themes = inputs.themes.map((t, i) => ({ id: i + 1, ...t }));
  const themeByName = new Map(themes.map((t) => [t.name.toLowerCase(), t]));
  const themeBySlug = new Map(themes.map((t) => [t.slug, t]));
  w.comment('themes');
  w.insert(
    'themes',
    themes.map((t) => ({
      id: t.id,
      slug: t.slug,
      name: t.name,
      vendor: t.vendor,
      vendor_slug: t.vendor ? slugify(t.vendor) : null,
      theme_store_id: t.theme_store_id,
      price_cents: priceToCents(t.price),
      price_label: t.price,
      marketplace: t.marketplace,
      official_url: t.official_url,
      status: 'active',
      created_at: CATALOG_TS,
      updated_at: CATALOG_TS,
    })),
  );

  // ------------------------------------------------------------------------------------------
  // Stores (930 detected; 20 curated merged in) + detection history
  // ------------------------------------------------------------------------------------------
  const curatedByDomain = new Map(
    inputs.curatedStores.map((s) => [normalizeDomain(s.domain) ?? s.domain, s]),
  );
  const curation = new Map(inputs.storeCuration.stores.map((s) => [s.domain, s]));
  for (const domain of curation.keys()) {
    if (!curatedByDomain.has(domain)) warn(`curation for unknown curated store ${domain}`);
  }
  const storeCategories = [
    ...new Set(
      inputs.storeCuration.stores.map((s) => s.category).filter((c): c is string => !!c),
    ),
  ].sort((a, b) => a.localeCompare(b));
  w.comment('store_categories');
  w.insert(
    'store_categories',
    storeCategories.map((name, i) => ({ id: i + 1, slug: slugify(name), name })),
  );

  // Curated stores first (in curation order), then the rest by domain.
  const ordered = [
    ...inputs.curatedStores.map((c) => {
      const d = detections.find((x) => x.domain === normalizeDomain(c.domain));
      if (!d) throw new Error(`Curated store ${c.domain} missing from detections`);
      return d;
    }),
    ...detections
      .filter((d) => !curatedByDomain.has(d.domain))
      .sort((a, b) => a.domain.localeCompare(b.domain)),
  ];

  const storeRows: Row[] = [];
  const storeThemeRows: Row[] = [];
  const storeAppRows: Row[] = [];
  const unresolvedRows: Row[] = [];
  const pixelRows: Row[] = [];
  const scanRows: Row[] = [];
  const appStoreCounts: Record<string, number> = {};
  const themeStoreCounts: Record<string, number> = {};
  const storeIdByDomain = new Map<string, number>();
  const storeApps = new Map<number, AppRecord[]>();
  const storeThemeId = new Map<number, number | null>();

  ordered.forEach((d, i) => {
    const id = i + 1;
    const seen = iso(d.detected_at);
    const curated = curatedByDomain.get(d.domain);
    const edit = curation.get(d.domain);
    storeIdByDomain.set(d.domain, id);

    const rawTheme = curated?.theme?.raw_name ?? d.theme;
    const theme = rawTheme ? themeByName.get(rawTheme.toLowerCase()) : undefined;
    storeThemeId.set(id, theme?.id ?? null);
    if (theme) themeStoreCounts[theme.slug] = (themeStoreCounts[theme.slug] ?? 0) + 1;

    storeRows.push({
      id,
      domain: d.domain,
      name: edit?.name ?? null,
      url: curated?.url ?? null,
      country: edit?.country ?? null,
      currency: curated?.currency ?? d.currency,
      category_slug: edit?.category ? slugify(edit.category) : null,
      tranco_rank: curated?.tranco_rank ?? null,
      is_curated: curated ? 1 : 0,
      status: 'active',
      opted_out_at: null,
      first_seen: seen,
      last_seen: seen,
      created_at: seen,
      updated_at: seen,
    });
    storeThemeRows.push({
      id,
      store_id: id,
      theme_id: theme?.id ?? null,
      raw_name: rawTheme,
      version: curated?.theme?.version ?? null,
      is_custom: d.theme_custom ? 1 : 0,
      first_seen: seen,
      last_seen: seen,
      replaced_at: null,
    });

    const confidence = new Map((curated?.apps ?? []).map((a) => [a.slug, a.confidence]));
    const resolved = new Map<number, AppRecord>();
    for (const slug of d.apps) {
      const app = resolveApp(slug);
      if (!app) {
        unresolvedRows.push({
          store_id: id,
          detection_slug: slug,
          first_seen: seen,
          last_seen: seen,
          removed_at: null,
        });
        continue;
      }
      if (resolved.has(app.id)) continue; // alias + canonical both detected
      resolved.set(app.id, app);
      appStoreCounts[app.slug] = (appStoreCounts[app.slug] ?? 0) + 1;
      storeAppRows.push({
        store_id: id,
        app_id: app.id,
        confidence: confidence.get(slug) ?? null,
        first_seen: seen,
        last_seen: seen,
        removed_at: null,
      });
    }
    storeApps.set(id, [...resolved.values()]);

    for (const pixel of curated?.pixels ?? []) {
      if (!(pixel in PIXELS)) warn(`store ${d.domain}: pixel '${pixel}' has no display name`);
      pixelRows.push({ store_id: id, pixel, first_seen: seen, last_seen: seen, removed_at: null });
    }
    scanRows.push({
      id,
      store_id: id,
      ran_at: seen,
      rules_version: SEED_CONSTANTS.rulesVersion,
      source: SEED_CONSTANTS.sourceId,
      http_status: null,
      raw_json: null,
    });
  });

  w.comment('stores + detection history');
  w.insert('stores', storeRows);
  w.insert('scans', scanRows);
  w.insert('store_themes', storeThemeRows);
  w.insert('store_apps', storeAppRows);
  w.insert('store_unresolved_apps', unresolvedRows);
  w.insert('store_pixels', pixelRows);

  // Cross-check our counts against the export's precomputed numbers.
  for (const a of allAppInputs) {
    const canonical = aliasOf.get(a.slug) ?? a.slug;
    if (canonical !== a.slug) continue;
    const ours = appStoreCounts[a.slug] ?? 0;
    if (ours !== a.scan.stores) {
      warn(`MISMATCH app ${a.slug}: detections=${ours} export=${a.scan.stores}`);
    }
    if (a.scan.pct_of_scanned !== undefined) {
      const pct = Math.round((ours / scannedTotal) * 10000) / 100;
      if (Math.abs(pct - a.scan.pct_of_scanned) > 0.01) {
        warn(`MISMATCH app ${a.slug} share: ${pct}% vs export ${a.scan.pct_of_scanned}%`);
      }
    }
  }
  for (const t of themes) {
    const ours = themeStoreCounts[t.slug] ?? 0;
    if (ours !== t.scan.stores) {
      warn(`MISMATCH theme ${t.slug}: detections=${ours} export=${t.scan.stores}`);
    }
  }
  checkCoInstalls(inputs.apps, storeApps, (slug) => resolveApp(slug) !== undefined, warn);

  // ------------------------------------------------------------------------------------------
  // Placeholder capture plan for curated stores
  // ------------------------------------------------------------------------------------------
  const pageRows: Row[] = [];
  const shotRows: Row[] = [];
  const sectionRows: Row[] = [];
  const shotHeights: SeedReport['shotHeights'] = [];
  /** domain → page|device|type → first section/screenshot id (for teardown notes). */
  const sectionIndex = new Map<string, Map<string, { sectionId: number; shotId: number }>>();

  for (const curated of inputs.curatedStores) {
    const domain = normalizeDomain(curated.domain) ?? curated.domain;
    const storeId = storeIdByDomain.get(domain);
    if (!storeId) continue;
    const layoutApps: LayoutApp[] = (storeApps.get(storeId) ?? []).map((a) => ({
      slug: a.slug,
      category: a.categoryName,
      storeCount: appStoreCounts[a.slug] ?? 0,
    }));
    const themeId = storeThemeId.get(storeId) ?? null;
    const index = new Map<string, { sectionId: number; shotId: number }>();
    sectionIndex.set(domain, index);
    const pageIds = new Map<string, number>();

    for (const shot of planStoreCaptures(domain, layoutApps)) {
      let pageId = pageIds.get(shot.pageType);
      if (pageId === undefined) {
        pageId = pageRows.length + 1;
        pageIds.set(shot.pageType, pageId);
        pageRows.push({
          id: pageId,
          store_id: storeId,
          page_type: shot.pageType,
          url: null,
          is_placeholder: 1,
          created_at: CATALOG_TS,
        });
      }
      const shotId = shotRows.length + 1;
      shotRows.push({
        id: shotId,
        page_id: pageId,
        store_id: storeId,
        page_type: shot.pageType,
        device: shot.device,
        viewport_w: shot.viewport,
        width: shot.width,
        height: shot.height,
        bytes: null,
        r2_key: null,
        captured_at: null,
        theme_id: themeId,
        is_current: 1,
        is_placeholder: 1,
        created_at: CATALOG_TS,
      });
      shotHeights.push({ domain, page: shot.pageType, device: shot.device, height: shot.height });
      shot.sections.forEach((s, order) => {
        const sectionId = sectionRows.length + 1;
        const appId = s.appSlug ? (appBySlug.get(s.appSlug)?.id ?? null) : null;
        sectionRows.push({
          id: sectionId,
          screenshot_id: shotId,
          section_type: s.type,
          y: s.y,
          height: s.height,
          x: s.x,
          w: s.w,
          order_index: order,
          app_id: appId,
          theme_section_name: null,
          r2_key_crop: null,
          is_placeholder: 1,
          hints_json: JSON.stringify(s.hints),
          store_id: storeId,
          page_type: shot.pageType,
          device: shot.device,
          theme_id: themeId,
          is_current: 1,
        });
        const key = `${shot.pageType}|${shot.device}|${s.type}`;
        if (!index.has(key)) index.set(key, { sectionId, shotId });
      });
    }
  }
  w.comment('placeholder capture plan (is_placeholder = 1; real captures replace these rows)');
  w.insert('pages', pageRows);
  w.insert('screenshots', shotRows);
  w.insert('sections', sectionRows);

  // ------------------------------------------------------------------------------------------
  // Teardowns
  // ------------------------------------------------------------------------------------------
  const teardownRows: Row[] = [];
  const noteRows: Row[] = [];
  for (const file of inputs.teardowns) {
    const { frontmatter: fm, body } = parseTeardown(file.file, file.source);
    const domain = normalizeDomain(fm.store);
    const storeId = domain ? storeIdByDomain.get(domain) : undefined;
    if (!domain || !storeId) throw new Error(`${file.file}: unknown store ${fm.store}`);
    const id = teardownRows.length + 1;
    teardownRows.push({
      id,
      slug: fm.slug,
      store_id: storeId,
      title: fm.title,
      dek: fm.dek ?? null,
      body_md: body,
      published_at: fm.published_at ?? null,
      is_sample: fm.is_sample ? 1 : 0,
      created_at: CATALOG_TS,
      updated_at: CATALOG_TS,
    });
    for (const note of fm.notes) {
      const hit = sectionIndex.get(domain)?.get(`${note.page_type}|${note.device}|${note.section_type}`);
      if (!hit) {
        warn(`${file.file}: note ${note.n} (${note.page_type}/${note.device}/${note.section_type}) has no matching section`);
      }
      noteRows.push({
        id: noteRows.length + 1,
        teardown_id: id,
        n: note.n,
        page_type: note.page_type,
        device: note.device,
        section_type: note.section_type,
        screenshot_id: hit?.shotId ?? null,
        section_id: hit?.sectionId ?? null,
        title: note.title,
        body: note.body,
      });
    }
  }
  w.comment('teardowns');
  w.insert('teardowns', teardownRows);
  w.insert('teardown_notes', noteRows);

  // ------------------------------------------------------------------------------------------
  // Popular comparisons
  // ------------------------------------------------------------------------------------------
  const comparisonRows: Row[] = [];
  const seenPairs = new Set<string>();
  const addPair = (kind: 'app' | 'theme', a: { id: number; slug: string }, b: { id: number; slug: string }, reason: string) => {
    const [x, y] = a.slug < b.slug ? [a, b] : [b, a];
    const slug = `${x.slug}-vs-${y.slug}`;
    if (seenPairs.has(slug)) return;
    seenPairs.add(slug);
    comparisonRows.push({
      id: comparisonRows.length + 1,
      kind,
      a_id: x.id,
      b_id: y.id,
      slug,
      reason,
      position: comparisonRows.length,
      body_md: null,
      created_at: CATALOG_TS,
    });
  };
  const usage = (slug: string) => appStoreCounts[slug] ?? 0;
  for (const category of categoryNames) {
    const top = apps
      .filter((a) => a.categoryName === category && usage(a.slug) > 0)
      .sort((a, b) => usage(b.slug) - usage(a.slug) || a.slug.localeCompare(b.slug))
      .slice(0, 3);
    for (let i = 0; i < top.length; i++) {
      for (let j = i + 1; j < top.length; j++) {
        const a = top[i];
        const b = top[j];
        if (a && b) addPair('app', a, b, 'category-top');
      }
    }
  }
  const themesByUsage = [...themes].sort(
    (a, b) =>
      (themeStoreCounts[b.slug] ?? 0) - (themeStoreCounts[a.slug] ?? 0) ||
      a.slug.localeCompare(b.slug),
  );
  const topThemes = themesByUsage.slice(0, 4);
  for (let i = 0; i < topThemes.length; i++) {
    for (let j = i + 1; j < topThemes.length; j++) {
      const a = topThemes[i];
      const b = topThemes[j];
      if (a && b) addPair('theme', a, b, 'usage-top');
    }
  }
  for (let i = 0; i < themesByUsage.length; i++) {
    for (let j = i + 1; j < themesByUsage.length; j++) {
      const a = themesByUsage[i];
      const b = themesByUsage[j];
      if (a && b && a.vendor && a.vendor === b.vendor) addPair('theme', a, b, 'same-vendor');
    }
  }
  w.comment('comparisons');
  w.insert('comparisons', comparisonRows);

  // ------------------------------------------------------------------------------------------
  // Affiliate programs and links (URLs live only in data; the API exposes /go/<id>)
  // ------------------------------------------------------------------------------------------
  const programKey = (name: string) => slugify(name.replace(/\(.*?\)/g, ''));
  const programs = inputs.programs.map((p, i) => ({ id: i + 1, key: programKey(p.program), ...p }));
  w.comment('affiliate');
  w.insert(
    'affiliate_programs',
    programs.map((p) => ({
      id: p.id,
      slug: p.key,
      name: p.program,
      network: p.network,
      status: p.status,
    })),
  );
  const linkRows: Row[] = inputs.links.map((l, i) => {
    let targetId: number | null = null;
    let targetName = l.target_name ?? l.target_slug ?? '';
    if (l.target_type === 'app') {
      const app =
        (l.target_slug ? resolveApp(l.target_slug) : undefined) ??
        apps.find((a) => a.input.affiliate?.url === l.url) ??
        apps.find((a) => a.input.name.toLowerCase() === targetName.toLowerCase());
      if (app) {
        targetId = app.id;
        targetName = l.target_name ?? app.input.name;
      }
    } else if (l.target_type === 'theme') {
      const theme =
        (l.target_slug ? themeBySlug.get(l.target_slug) : undefined) ??
        themes.find((t) => t.affiliate?.url === l.url) ??
        themeByName.get(targetName.toLowerCase());
      if (theme) {
        targetId = theme.id;
        targetName = l.target_name ?? theme.name;
      }
    }
    if (l.target_slug && targetId === null) warn(`affiliate link ${i + 1}: unknown target ${l.target_slug}`);
    const program = l.program ? programs.find((p) => p.key === programKey(l.program ?? '')) : undefined;
    if (l.program && !program) warn(`affiliate link ${i + 1}: unknown program '${l.program}'`);
    return {
      id: i + 1,
      target_type: l.target_type,
      target_id: targetId,
      target_name: targetName,
      program_id: program?.id ?? null,
      url: l.url,
      label: 'Affiliate link',
      active: 1,
      created_at: CATALOG_TS,
      updated_at: CATALOG_TS,
    };
  });
  w.insert('affiliate_links', linkRows);

  // ------------------------------------------------------------------------------------------
  // Derived tables: the same SQL ingest/admin run (src/server/repo/maintenance.ts)
  // ------------------------------------------------------------------------------------------
  w.comment('derived tables (src/server/repo/maintenance.ts)');
  for (const sql of REBUILD_DERIVED_SQL) w.raw(sql);

  const counts = Object.fromEntries(w.rowCounts());
  return {
    sql: w.toString(),
    report: { dataVersion, counts, warnings, appStoreCounts, themeStoreCounts, shotHeights },
  };
}

/** Compares our co-install ranking with the export's `scan.co_installed` (order-insensitive). */
function checkCoInstalls(
  apps: readonly AppInput[],
  storeApps: ReadonlyMap<number, AppRecord[]>,
  resolvable: (detectionSlug: string) => boolean,
  warn: (msg: string) => void,
): void {
  const pairs = new Map<string, Map<string, number>>();
  for (const list of storeApps.values()) {
    for (const a of list) {
      const m = pairs.get(a.slug) ?? new Map<string, number>();
      pairs.set(a.slug, m);
      for (const b of list) if (a !== b) m.set(b.slug, (m.get(b.slug) ?? 0) + 1);
    }
  }
  for (const a of apps) {
    // Only resolved apps take part in co-install stats; unresolved detection slugs are skipped.
    const expected = a.scan.co_installed?.filter((s) => resolvable(s));
    if (!expected?.length) continue;
    const ranked = [...(pairs.get(a.slug) ?? new Map<string, number>()).entries()].sort(
      (x, y) => y[1] - x[1],
    );
    // Allow ties at the cut-off: everything with a count >= the n-th count qualifies.
    const cutoff = ranked[expected.length - 1]?.[1] ?? 0;
    const qualifying = new Set(ranked.filter(([, n]) => n >= cutoff).map(([s]) => s));
    const missing = expected.filter((s) => !qualifying.has(s));
    if (missing.length) warn(`co-installs for ${a.slug}: export lists ${missing.join(', ')} outside our top ${expected.length}`);
  }
}
